CREATE TABLE TIPO_PGTO(
	PK_TIPO_PGTO INT PRIMARY KEY,
	DESC_TIPO_PGTO VARCHAR(20) NOT NULL
)

CREATE TABLE PEDIDO(
	PK_PEDIDO INT PRIMARY KEY,
	PRODUTO VARCHAR(20) NOT NULL,
	VALOR_PEDIDO FLOAT,
	FK_TP_PGTO INT,
	FOREIGN KEY (FK_TP_PGTO) REFERENCES TIPO_PGTO (PK_TIPO_PGTO)
)

